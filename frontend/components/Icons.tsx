export const WORKSPACE_ICON_MAP: Record<string, React.ComponentType<{ className?: string }>> = {
  users: Users,
  briefcase: Briefcase,
  folder: Folder,
  sparkles: Sparkles,
  code: Code,
  rocket: Rocket,
  palette: Palette,
  globe: Globe,
  lightning: Zap,
  star: Star,
  book: Book,
  building: Building,
  flame: Flame,
  heart: Heart,
  compass: Compass,
  checkCircle: CheckCircle2,
  tag: Tag,
  trophy: Trophy,
  terminal: Terminal,
  cloud: Cloud,
  shield: Shield,
  layers: Layers,
  cpu: Cpu,
  messageSquare: MessageSquare,
};

export function WorkspaceIcon({ name, className = 'w-4 h-4' }: { name: string; className?: string }) {
  const IconComponent = WORKSPACE_ICON_MAP[name] || Briefcase;
  return <IconComponent className={className} />;
}

